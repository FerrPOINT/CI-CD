const SEED: &str = "CREATE TABLE public.records (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,payload text NOT NULL);\n";
const NEXT: &str = "ALTER TABLE public.records ADD COLUMN note text NULL;";

fn docker(args: &[&str]) -> serde_json::Value {
    let output = std::process::Command::new("docker")
        .args(args)
        .output()
        .unwrap();
    assert!(output.status.success(), "Docker QA inspection failed");
    serde_json::from_slice(&output.stdout).unwrap()
}
fn compose(project: &str, file: &std::path::Path, args: &[&str]) {
    let status = std::process::Command::new("/usr/local/bin/docker-compose")
        .args(["-p", project, "-f"])
        .arg(file)
        .args(args)
        .status()
        .unwrap();
    if !status.success() {
        let _ = std::process::Command::new("/usr/local/bin/docker-compose")
            .args(["-p", project, "-f"])
            .arg(file)
            .args(["logs", "--tail", "50", "database"])
            .status();
    }
    assert!(status.success(), "Owned Compose operation failed");
}
struct PgCleanup {
    project: String,
    file: PathBuf,
}
impl Drop for PgCleanup {
    fn drop(&mut self) {
        compose(&self.project, &self.file, &["down", "--remove-orphans"]);
        let volume = format!("{}_postgres-data", self.project);
        let inventory = std::process::Command::new("docker")
            .args([
                "volume",
                "ls",
                "-q",
                "--filter",
                &format!("name=^{volume}$"),
            ])
            .output()
            .unwrap();
        assert!(inventory.status.success());
        if inventory.stdout.is_empty() {
            return;
        }
        let actual = docker(&["volume", "inspect", &volume]);
        assert_eq!(
            actual[0]["Labels"]["com.docker.compose.project"],
            self.project
        );
        assert_eq!(actual[0]["Labels"]["sdlc.task"], "forge-task-delivery");
        assert!(
            std::process::Command::new("docker")
                .args(["volume", "rm", &volume])
                .status()
                .unwrap()
                .success()
        );
    }
}
struct Pg {
    t: ActualDelivery,
    root: PathBuf,
    policy: PathBuf,
    config: serde_json::Value,
    project: String,
    compose_root: PathBuf,
    password: String,
    _cleanup: PgCleanup,
}
impl Drop for Pg {
    fn drop(&mut self) {
        fn copy_json(source: &std::path::Path, target: &std::path::Path) {
            std::fs::create_dir_all(target).unwrap();
            for entry in std::fs::read_dir(source).unwrap().flatten() {
                let path = entry.path();
                let next = target.join(entry.file_name());
                if path.is_dir() {
                    copy_json(&path, &next);
                } else if path.extension().is_some_and(|x| x == "json") {
                    std::fs::copy(path, next).unwrap();
                }
            }
        }
        let export =
            PathBuf::from("/output/pg-evidence").join(self.compose_root.file_name().unwrap());
        std::fs::create_dir_all(&export).unwrap();
        for name in ["operations", "manifests", "backups"] {
            let folder = self.root.join(name);
            if folder.exists() {
                copy_json(&folder, &export.join(name));
            }
        }
        // Actual generated Compose files are retained on the host for panic cleanup/audit.
        let mut files = std::fs::read_dir(&self.compose_root)
            .unwrap()
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|e| e == "json"))
            .collect::<Vec<_>>();
        files.sort_by_key(|p| std::fs::metadata(p).unwrap().modified().unwrap());
        let file = files.last().unwrap();
        std::fs::copy(file, "/output/pg-compose.json").unwrap();
    }
}
