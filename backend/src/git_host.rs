async fn resolve_repo_path(
    pool: &PgPool,
    config: &GitConfig,
    raw: &str,
) -> Result<PathBuf, ApiError> {
    let name = validate_repo_name(raw).map_err(ApiError::bad_request)?;
    let exists =
        sqlx::query_scalar::<_, bool>("SELECT EXISTS(SELECT 1 FROM repositories WHERE name = $1)")
            .bind(&name)
            .fetch_one(pool)
            .await
            .map_err(ApiError::internal)?;
    if !exists {
        return Err(ApiError::not_found());
    }
    Ok(repo_path(&config.root, &name))
}

#[derive(Deserialize, utoipa::ToSchema)]
pub struct GitPushEvent {
    pub repository: String,
    pub ref_name: String,
    #[serde(default)]
    pub old_rev: Option<String>,
    #[serde(default)]
    pub new_rev: Option<String>,
}

/// Internal endpoint called by the generated `post-receive` hook.
/// Finds a project whose repository_url points at this repo and triggers a pipeline.
#[utoipa::path(
    post,
    path = "/api/v1/internal/git-push",
    tag = "git",
    request_body = GitPushEvent,
    responses(
        (status = 200, description = "Pipeline trigger decision"),
        (status = 400),
        (status = 401),
    ),
)]
pub async fn internal_git_push(
    State(state): State<std::sync::Arc<AppState>>,
    headers: HeaderMap,
    axum::Json(event): axum::Json<GitPushEvent>,
) -> Result<axum::Json<serde_json::Value>, ApiError> {
    if let Some(expected) = configured_internal_token(state.git.internal_token.as_deref()) {
        let provided = headers
            .get("x-internal-token")
            .and_then(|v| v.to_str().ok())
            .unwrap_or("");
        if provided != expected {
            return Err(ApiError::unauthorized());
        }
    }
    let pool = state.pool.as_ref().ok_or_else(ApiError::unavailable)?;
    let name = validate_repo_name(&event.repository).map_err(ApiError::bad_request)?;
    let short_ref = event
        .ref_name
        .strip_prefix("refs/heads/")
        .or_else(|| event.ref_name.strip_prefix("refs/tags/"))
        .unwrap_or(&event.ref_name)
        .to_string();
    if event.new_rev.as_deref().is_some_and(is_zero_object_id) {
        return Ok(axum::Json(serde_json::json!({
            "triggered": false,
            "pipeline_id": null,
            "reason": "deleted_ref"
        })));
    }
    let idempotency_key = event
        .new_rev
        .as_deref()
        .filter(|rev| is_probable_object_id(rev))
        .map(|rev| git_push_idempotency_key(&name, &event.ref_name, rev));
    let patterns = repository_url_like_patterns(&name);
    let project_id: Option<Uuid> = sqlx::query_scalar(
        "SELECT id FROM projects \
             WHERE repository_url ILIKE $1 ESCAPE '\\' \
                OR repository_url ILIKE $2 ESCAPE '\\' \
                OR repository_url ILIKE $3 ESCAPE '\\' \
             LIMIT 1",
    )
    .bind(&patterns.path)
    .bind(&patterns.scp)
    .bind(&patterns.exact)
    .fetch_optional(pool)
    .await
    .map_err(ApiError::internal)?;
    match project_id {
        Some(project_id) => {
            let outcome = crate::api::create_pipeline_with_vars_idempotent(
                pool,
                project_id,
                short_ref,
                serde_json::json!({}),
                crate::api::PIPELINE_TRIGGER_SOURCE_GIT_PUSH,
                idempotency_key.as_deref(),
            )
            .await?;
            Ok(axum::Json(serde_json::json!({
                "triggered": true,
                "pipeline_id": outcome.pipeline.id,
                "replayed": outcome.replayed
            })))
        }
        None => Ok(axum::Json(
            serde_json::json!({"triggered": false, "pipeline_id": null}),
        )),
    }
}

fn is_zero_object_id(value: &str) -> bool {
    value.len() >= 40 && value.chars().all(|c| c == '0')
}

fn is_probable_object_id(value: &str) -> bool {
    value.len() >= 40 && value.chars().all(|c| c.is_ascii_hexdigit())
}

fn git_push_idempotency_key(repository: &str, ref_name: &str, new_rev: &str) -> String {
    use sha2::{Digest, Sha256};
    let payload = format!("{repository}\0{ref_name}\0{new_rev}");
    format!("git-push:{:x}", Sha256::digest(payload.as_bytes()))
}

// --- Axum HTTP handlers (thin wrappers over the core functions) ---

#[derive(Deserialize, utoipa::ToSchema)]
pub struct CreateRepositoryBody {
    pub name: String,
    #[serde(default)]
    pub visibility: Option<String>,
}

#[derive(Debug, serde::Serialize, utoipa::ToSchema)]
pub struct DeletedRepository {
    pub deleted: String,
}

#[utoipa::path(
    post,
    path = "/api/v1/repositories",
    tag = "repos",
    request_body = CreateRepositoryBody,
    responses(
        (status = 200, body = Repository),
        (status = 400),
        (status = 503),
    ),
)]
pub async fn create_repository(
    State(state): State<std::sync::Arc<AppState>>,
    axum::Json(body): axum::Json<CreateRepositoryBody>,
) -> Result<axum::Json<Repository>, ApiError> {
    let pool = state.pool.as_ref().ok_or_else(ApiError::unavailable)?;
    let repo =
        create_repository_core(pool, &state.git, &body.name, body.visibility.as_deref()).await?;
    Ok(axum::Json(repo))
}

#[utoipa::path(
    get,
    path = "/api/v1/repositories",
    tag = "repos",
    responses(
        (status = 200, body = [Repository]),
        (status = 503),
    ),
)]
pub async fn list_repositories(
    State(state): State<std::sync::Arc<AppState>>,
) -> Result<axum::Json<Vec<Repository>>, ApiError> {
    let pool = state.pool.as_ref().ok_or_else(ApiError::unavailable)?;
    let repos = list_repositories_core(pool).await?;
    Ok(axum::Json(repos))
}

#[utoipa::path(
    delete,
    path = "/api/v1/repositories/{name}",
    tag = "repos",
    params(("name" = String, Path, description = "Repository name")),
    responses(
        (status = 200, body = DeletedRepository),
        (status = 404),
        (status = 503),
    ),
)]
pub async fn delete_repository(
    State(state): State<std::sync::Arc<AppState>>,
    AxumPath(name): AxumPath<String>,
) -> Result<axum::Json<DeletedRepository>, ApiError> {
    let pool = state.pool.as_ref().ok_or_else(ApiError::unavailable)?;
    delete_repository_core(pool, &state.git, &name).await?;
    Ok(axum::Json(DeletedRepository {
        deleted: name.trim_end_matches(".git").to_string(),
    }))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn validates_repo_names() {
        assert!(validate_repo_name("demo").is_ok());
        assert!(validate_repo_name("demo.git").is_ok());
        assert_eq!(validate_repo_name("demo.git").expect("valid name"), "demo");
        assert!(validate_repo_name("").is_err());
        assert!(validate_repo_name("../etc").is_err());
        assert!(validate_repo_name(".hidden").is_err());
        assert!(validate_repo_name("a..b").is_err());
        assert!(validate_repo_name("has space").is_err());
        assert!(validate_repo_name("спец").is_err());
    }

    #[test]
    fn pkt_line_prefix_is_hex_length() {
        let line = pkt_line("# service=git-upload-pack\n");
        assert_eq!(&line[..4], b"001e");
        assert!(line.ends_with(b"# service=git-upload-pack\n"));
    }

    #[test]
    fn escapes_like_wildcards_in_repository_binding() {
        assert_eq!(escape_like_pattern("service_api"), "service\\_api");
        assert_eq!(
            repository_url_like_patterns("service_api"),
            RepositoryUrlPatterns {
                path: "%/service\\_api.git".to_string(),
                scp: "%:service\\_api.git".to_string(),
                exact: "service\\_api.git".to_string(),
            }
        );
    }

    #[tokio::test]
    async fn creates_and_deletes_bare_repository() {
        let dir = std::env::temp_dir().join(format!("forge-git-test-{}", Uuid::new_v4()));
        let config = GitConfig {
            root: dir.clone(),
            token: None,
            internal_token: Some("test-internal".into()),
        };
        tokio::fs::create_dir_all(&dir)
            .await
            .expect("create temp dir");
        // Minimal in-memory check is impossible without Postgres; verify hook + git layout directly.
        let path = repo_path(&dir, "demo");
        let status = Command::new("git")
            .args(["init", "--bare", "--quiet"])
            .arg(&path)
            .status()
            .await
            .expect("git init");
        assert!(status.success());
        assert!(path.join("HEAD").exists());
        let hook = post_receive_hook("demo", config.internal_token.as_deref());
        assert!(hook.contains("x-internal-token: test-internal"));
        assert!(hook.contains("demo"));
        assert!(hook.contains("$refname"));
        assert!(hook.contains("$oldrev"));
        assert!(hook.contains("$newrev"));
        assert!(hook.contains("/api/v1/internal/git-push"));
        let key = git_push_idempotency_key(
            "demo",
            "refs/heads/main",
            "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
        );
        assert!(key.starts_with("git-push:"));
        assert_ne!(
            key,
            git_push_idempotency_key(
                "demo",
                "refs/heads/main",
                "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"
            )
        );
        let _ = tokio::fs::remove_dir_all(&dir).await;
    }

    #[test]
    fn post_receive_hook_omits_blank_internal_token() {
        let hook = post_receive_hook("demo", Some(" \t "));
        assert!(!hook.contains("x-internal-token"));
        assert!(hook.contains("/api/v1/internal/git-push"));
    }

    #[test]
    fn post_receive_hook_without_token_keeps_valid_shell_continuation() {
        let hook = post_receive_hook("demo", None);
        // No blank line may sit between a backslash continuation and the next
        // curl argument: that truncated the command before `-d` and broke
        // push-triggered pipelines on deployments without an internal token.
        for (index, line) in hook.lines().enumerate() {
            if line.trim_end().ends_with('\\') {
                let next = hook
                    .lines()
                    .nth(index + 1)
                    .expect("continuation must be followed by a line");
                assert!(
                    !next.trim().is_empty(),
                    "blank continuation line in hook:\n{hook}"
                );
            }
        }
        // The generator emits shell-escaped JSON: \"repository\":\"demo\".
        assert!(hook.contains("\\\"repository\\\":\\\"demo\\\""));
    }

    #[test]
    fn post_receive_hook_with_token_keeps_valid_shell_continuation() {
        let hook = post_receive_hook("demo", Some("secret-token"));
        assert!(hook.contains("x-internal-token: secret-token"));
        for (index, line) in hook.lines().enumerate() {
            if line.trim_end().ends_with('\\') {
                let next = hook
                    .lines()
                    .nth(index + 1)
                    .expect("continuation must be followed by a line");
                assert!(
                    !next.trim().is_empty(),
                    "blank continuation line in hook:\n{hook}"
                );
            }
        }
    }
}
