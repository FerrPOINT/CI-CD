async fn resolve_repo_path(
    pool: &PgPool,
    config: &GitConfig,
    raw: &str,
) -> Result<PathBuf, ApiError> {
    let name = validate_repo_name(raw).map_err(ApiError::bad_request)?;
    let exists =
        sqlx::query_scalar::<_, bool>("SELECT EXISTS(SELECT 1 FROM repositories WHERE name = $1)")
            .bind(&name)
            .fetch_one(pool)
            .await
            .map_err(ApiError::internal)?;
    if !exists {
        return Err(ApiError::not_found());
    }
    Ok(repo_path(&config.root, &name))
}

#[derive(Deserialize, utoipa::ToSchema)]
pub struct GitPushEvent {
    pub repository: String,
    pub ref_name: String,
    #[serde(default)]
    pub old_rev: Option<String>,
    #[serde(default)]
    pub new_rev: Option<String>,
}

/// Internal endpoint called by the generated `post-receive` hook.
/// Finds a project whose repository_url points at this repo and triggers a pipeline.
#[utoipa::path(
    post,
    path = "/api/v1/internal/git-push",
    tag = "git",
    request_body = GitPushEvent,
    responses(
        (status = 200, description = "Pipeline trigger decision"),
        (status = 400),
        (status = 401),
    ),
)]
pub async fn internal_git_push(
    State(state): State<std::sync::Arc<AppState>>,
    headers: HeaderMap,
    axum::Json(event): axum::Json<GitPushEvent>,
) -> Result<axum::Json<serde_json::Value>, ApiError> {
    if let Some(expected) = state.git.internal_token.as_deref() {
        if !expected.is_empty() {
            let provided = headers
                .get("x-internal-token")
                .and_then(|v| v.to_str().ok())
                .unwrap_or("");
            if provided != expected {
                return Err(ApiError::unauthorized());
            }
        }
    }
    let pool = state.pool.as_ref().ok_or_else(ApiError::unavailable)?;
    let name = validate_repo_name(&event.repository).map_err(ApiError::bad_request)?;
    let short_ref = event
        .ref_name
        .strip_prefix("refs/heads/")
        .or_else(|| event.ref_name.strip_prefix("refs/tags/"))
        .unwrap_or(&event.ref_name)
        .to_string();
    if event.new_rev.as_deref().is_some_and(is_zero_object_id) {
        return Ok(axum::Json(serde_json::json!({
            "triggered": false,
            "pipeline_id": null,
            "reason": "deleted_ref"
        })));
    }
    let idempotency_key = event
        .new_rev
        .as_deref()
        .filter(|rev| is_probable_object_id(rev))
        .map(|rev| git_push_idempotency_key(&name, &event.ref_name, rev));
    let pattern = format!("%{name}.git");
    let project_id: Option<Uuid> =
        sqlx::query_scalar("SELECT id FROM projects WHERE repository_url ILIKE $1 LIMIT 1")
            .bind(&pattern)
            .fetch_optional(pool)
            .await
            .map_err(ApiError::internal)?;
    match project_id {
        Some(project_id) => {
            let outcome = crate::api::create_pipeline_with_vars_idempotent(
                pool,
                project_id,
                short_ref,
                serde_json::json!({}),
                crate::api::PIPELINE_TRIGGER_SOURCE_GIT_PUSH,
                idempotency_key.as_deref(),
            )
            .await?;
            Ok(axum::Json(serde_json::json!({
                "triggered": true,
                "pipeline_id": outcome.pipeline.id,
                "replayed": outcome.replayed
            })))
        }
        None => Ok(axum::Json(
            serde_json::json!({"triggered": false, "pipeline_id": null}),
        )),
    }
}

fn is_zero_object_id(value: &str) -> bool {
    value.len() >= 40 && value.chars().all(|c| c == '0')
}

fn is_probable_object_id(value: &str) -> bool {
    value.len() >= 40 && value.chars().all(|c| c.is_ascii_hexdigit())
}

fn git_push_idempotency_key(repository: &str, ref_name: &str, new_rev: &str) -> String {
    use sha2::{Digest, Sha256};
    let payload = format!("{repository}\0{ref_name}\0{new_rev}");
    format!("git-push:{:x}", Sha256::digest(payload.as_bytes()))
}

